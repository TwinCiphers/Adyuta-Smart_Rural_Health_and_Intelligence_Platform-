import 'dart:convert';
import 'package:http/http.dart' as http;
import 'package:flutter_dotenv/flutter_dotenv.dart';

class GroqService {
  static String get apiKey => dotenv.env['GROQ_API_KEY'] ?? const String.fromEnvironment('GROQ_API_KEY', defaultValue: '');
  static const String _chatUrl = 'https://api.groq.com/openai/v1/chat/completions';
  static const String _audioUrl = 'https://api.groq.com/openai/v1/audio/transcriptions';

  static Future<String> askGroq(String query, {List<Map<String, dynamic>> history = const [], String? base64Image, String contextText = ''}) async {
    final messages = <Map<String, dynamic>>[
      {
        "role": "system",
        "content": "You are Aroha, an intelligent rural AI assistant for Adyuta. You help with Government Schemes, Statutory Laws, Health diagnosis, and Farming advice. Always identify yourself as Aroha when asked. Keep answers concise, helpful, and professional. You support multiple Indian languages perfectly. Do NOT add any disclaimers like 'I am an AI' or 'Note: This was generated by AI'."
      }
    ];

    for (var msg in history) {
      messages.add(msg);
    }

    if (base64Image != null && base64Image.isNotEmpty) {
      messages.add({
        "role": "user",
        "content": [
          {"type": "text", "text": query.isEmpty ? "What is in this image? Provide detailed analysis." : query},
          {
            "type": "image_url",
            "image_url": {
              "url": "data:image/jpeg;base64,$base64Image"
            }
          }
        ]
      });
    } else {
      String finalQuery = query;
      if (contextText.isNotEmpty) {
        finalQuery = "Context Information:\n$contextText\n\nBased on the above context, answer the following query: $query";
      }
      messages.add({
        "role": "user",
        "content": finalQuery
      });
    }

    final body = {
      "model": base64Image != null ? "qwen/qwen3.8-27b" : "openai/gpt-oss-20b",
      "messages": messages,
      "temperature": 0.5,
      "max_tokens": 1024,
    };

    final response = await http.post(
      Uri.parse(_chatUrl),
      headers: {
        'Authorization': 'Bearer $apiKey',
        'Content-Type': 'application/json',
      },
      body: jsonEncode(body),
    );

    if (response.statusCode == 200) {
      final data = jsonDecode(utf8.decode(response.bodyBytes));
      return data['choices'][0]['message']['content'];
    } else {
      throw Exception('Groq API error: ${response.statusCode} - ${response.body}');
    }
  }

  static Future<String> transcribeAudio(List<int> audioBytes, String filename) async {
    final request = http.MultipartRequest('POST', Uri.parse(_audioUrl));
    request.headers.addAll({
      'Authorization': 'Bearer $apiKey',
    });
    request.fields['model'] = 'whisper-large-v3';
    request.fields['response_format'] = 'json';
    
    request.files.add(http.MultipartFile.fromBytes(
      'file',
      audioBytes,
      filename: filename,
    ));

    final streamedResponse = await request.send();
    final response = await http.Response.fromStream(streamedResponse);

    if (response.statusCode == 200) {
      final data = jsonDecode(utf8.decode(response.bodyBytes));
      return data['text'] ?? '';
    } else {
      throw Exception('Groq STT error: ${response.statusCode} - ${response.body}');
    }
  }
}
