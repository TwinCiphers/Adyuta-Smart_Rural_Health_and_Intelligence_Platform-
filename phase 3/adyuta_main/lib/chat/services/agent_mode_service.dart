  /// Returns a local response if the input matches a common conversational intent.
  static String? matchIntent(String input) {
    final query = input.trim().toLowerCase();
    
    // Direct match
    if (_intents.containsKey(query)) {
      return _intents[query];
    }
    
    // Simple heuristic for punctuation variations
    final cleanQuery = query.replaceAll(RegExp(r'[^a-zA-Z0-9 ]'), '').trim();
    for (final key in _intents.keys) {
       final cleanKey = key.replaceAll(RegExp(r'[^a-zA-Z0-9 ]'), '').trim();
       if (cleanKey == cleanQuery && cleanKey.isNotEmpty) {
          return _intents[key];
       }
    }
    
    return null;
  }
