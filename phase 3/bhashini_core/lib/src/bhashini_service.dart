  String _currentLanguageCode = 'en';
  String get currentLanguageCode => _currentLanguageCode;
  
  Map<String, Map<String, String>> _cache = {};

  Future<void> _loadLanguage() async {
    final prefs = await SharedPreferences.getInstance();
    _currentLanguageCode = prefs.getString('bhashini_lang') ?? 'en';
    notifyListeners();
  }

  Future<void> setLanguage(String langCode) async {
    if (_currentLanguageCode == langCode) return;
    _currentLanguageCode = langCode;
    final prefs = await SharedPreferences.getInstance();
    await prefs.setString('bhashini_lang', langCode);
    notifyListeners();
  }

  Future<String> translate(String text) async {
    if (_currentLanguageCode == 'en' || text.trim().isEmpty) return text;
    
    
    if (_localTranslations[_currentLanguageCode] != null && _localTranslations[_currentLanguageCode]!.containsKey(text)) {
      return _localTranslations[_currentLanguageCode]![text]!;
    }
    if (_cache[_currentLanguageCode] != null && _cache[_currentLanguageCode]!.containsKey(text)) {
      return _cache[_currentLanguageCode]![text]!;
    }

    try {
      final url = Uri.parse('https://api.mymemory.translated.net/get?q=${Uri.encodeComponent(text)}&langpair=en|${_currentLanguageCode}');
      final response = await http.get(url).timeout(const Duration(seconds: 5));
      if (response.statusCode == 200) {
        final data = json.decode(response.body);
        final translatedText = data['responseData']['translatedText'];
        if (translatedText != null && translatedText.toString().trim().isNotEmpty) {
           _cache.putIfAbsent(_currentLanguageCode, () => {})[text] = translatedText;
           return translatedText;
        }
      }
    } catch (e) {
      // fallback to text
    }
    return text;
  }
